const STRINGS: Record<Lang, Record<StringKey, string>> = { de, en };

export function t(lang: Lang, key: StringKey): string {
  return STRINGS[lang][key];
}

/** Hook returning a translator bound to the user's language. */
export function useT() {
  const lang = useStore((s) => s.settings.lang);
  return Object.assign((key: StringKey) => STRINGS[lang][key], { lang });
}
